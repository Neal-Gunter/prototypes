// v29：拆解模式数据和本机库存的单元测试（node scripts/teardown-test.mjs）
import fs from "node:fs";
const store = {}; globalThis.localStorage = { getItem: (k) => (k in store ? store[k] : null), setItem: (k, v) => { store[k] = String(v); }, removeItem: (k) => { delete store[k]; } };
globalThis.window = { dispatchEvent() {} }; globalThis.Event = class { constructor(t) { this.type = t; } };
const { DEVICES, COMMON_SAFETY, UNVERIFIED, searchDevices, MAX_VOLTS, isMainsQuery } = await import("../src/teardown/devices.js");
const { TD_PROCEDURAL } = await import("../src/teardown/approxParts.js");
const { PROC_BY_ID } = await import("../src/assembly/procedural.js");
const inv = await import("../src/teardown/inventory.js");
const idx = JSON.parse(fs.readFileSync("public/lib/index.json", "utf8")); const REAL = new Set(idx.parts.map((r) => r[0]));
let pass = 0, fail = 0; const ok = (c, m, x = "") => { c ? pass++ : fail++; console.log(c ? "✓" : "✗", m, x); };
const CJK = /[\u4e00-\u9fff]/;
const pairs = [];
const walk = (o, path) => { if (o && typeof o === "object") { if ("zh" in o && "en" in o && Object.keys(o).length === 2) pairs.push([path, o]); else for (const [k, v] of Object.entries(o)) walk(v, path + "." + k); } };
walk(DEVICES, "D"); walk(COMMON_SAFETY, "S"); walk(UNVERIFIED, "U");
ok(DEVICES.length === 12, `12 台设备（v35 加了红外遥控器，v30 加了有线鼠标 / 蓝牙音箱 / 厨房秤，v31 加了 LED 手电 / TP4056 充电板，v32 加了 9V LED 测试器 / OTG 集线器，v33 加了 AA 电池玩具车）（${DEVICES.map((d) => d.id).join(", ")}）`);
ok(pairs.length >= 100, `中英成对文字 ${pairs.length} 条`);
const badPair = pairs.filter(([, o]) => !o.zh || !o.en || !CJK.test(o.zh) && !/^[\w\s().,-]+$/.test(o.zh) || CJK.test(o.en));
ok(badPair.length === 0, "每条都有中文和英文、英文里没有汉字", badPair.slice(0, 3).map((x) => x[0]).join(" "));
for (const d of DEVICES) {
  ok(d.steps.length >= 6 && d.steps.every((s) => s.t && s.d && s.fig), `${d.id}：${d.steps.length} 步，每步有标题 / 正文 / 插图`);
  const ids = new Set(d.fig.map((f) => f.id));
  const badFig = d.steps.flatMap((s) => [...(s.fig.hi || []), ...Object.keys(s.fig.off || {})]).filter((x) => !ids.has(x));
  ok(!badFig.length, `${d.id}：插图引用的图层都存在`, badFig.join(","));
  ok(d.steps.some((s) => s.stop), `${d.id}：至少一个停止点`);
  ok(d.materials.length >= 4 && d.safety.length >= 3, `${d.id}：材料 ${d.materials.length} 项、安全 ${d.safety.length} 条`);
  const missing = d.modules.filter((m) => !PROC_BY_ID[m.part] && !REAL.has(m.part));
  ok(!missing.length, `${d.id}：${d.modules.length} 个模块都能在零件库里找到`, missing.map((m) => m.part).join(","));
  const wrongApprox = d.modules.filter((m) => (m.match === "approx") !== !!PROC_BY_ID[m.part]?.approx);
  ok(!wrongApprox.length, `${d.id}：标“近似件”的模块正好是程序生成的近似件`, wrongApprox.map((m) => m.key).join(","));
  ok(d.modules.some((m) => m.match !== "approx"), `${d.id}：至少一个模块用了零件库已有件`);
}
const pb = DEVICES.find((d) => d.battery);
const iCut = pb.steps.findIndex((s) => /断开电芯/.test(s.t.zh)), iBoard = pb.steps.findIndex((s) => /控制板/.test(s.t.zh));
ok(pb.steps[0].stop && iCut > 0 && iCut < iBoard && /电池先处理/.test(pb.safety[0].zh), `含电池的设备：先检查（停止点）→ 断开电芯（第 ${iCut + 1} 步）→ 再碰控制板（第 ${iBoard + 1} 步）`);
ok(/先处理电池/.test(COMMON_SAFETY[0].zh) && COMMON_SAFETY.some((s) => /防静电/.test(s.zh)) && COMMON_SAFETY.some((s) => /停止点/.test(s.zh)), "通用安全：电池先处理 / 防静电 / 停止点");
ok(UNVERIFIED.zh === "按公开资料整理，未经实物验证", "未经实物验证标签");
ok(TD_PROCEDURAL.length === 36 && TD_PROCEDURAL.every((p) => p.approx && /近似件/.test(p.name_zh) && /approximate/.test(p.name) && p.est.length && p.dims_mm.x > 0 && p.dims_mm.y > 0 && p.dims_mm.z > 0 && p.colliders.length === p.proc.prims.length), "10 个近似件：名字标“近似件”、尺寸 > 0、标估算、碰撞盒齐全");
ok(TD_PROCEDURAL.every((p) => PROC_BY_ID[p.id]?.licence?.includes("CC0")), "近似件进了程序零件表（CC0）");
ok(searchDevices("sg90").length === 1 && searchDevices("充电宝").length === 1 && searchDevices("FAN").length === 1 && searchDevices("").length === 12 && searchDevices("玩具车").length === 1 && searchDevices("toy car").length === 1 && searchDevices("9v").length === 1 && searchDevices("OTG").length === 1 && searchDevices("tp4056").length === 1 && searchDevices("手电").length === 1 && searchDevices("zzz").length === 0, "搜索（大小写、中英文、空串、无结果）");
// v32：安全规则——只收低压直流设备，市电设备不收
ok(MAX_VOLTS === 24 && DEVICES.every((d) => typeof d.volts === "number" && d.volts > 0 && d.volts <= MAX_VOLTS), `每台设备都标了供电电压且 ≤ ${MAX_VOLTS} V（${DEVICES.map((d) => d.volts).join("/")}）`);
ok(DEVICES.every((d) => ![d.name.zh, d.name.en, d.model, ...d.alias].some(isMainsQuery)), "设备名 / 型号 / 别名里没有市电类设备");
ok(["充电头", "220V 电源适配器", "wall charger", "power supply", "微波炉"].every(isMainsQuery) && !["tp4056", "9v", "otg", "风扇"].some(isMainsQuery), "市电关键词识别（充电头 / 适配器 / wall charger 是，tp4056 / 9v / otg 不是）");
ok(COMMON_SAFETY.some((s) => /低压直流/.test(s.zh) && /市电/.test(s.zh) && /Mains/.test(s.en)), "通用安全里有“只收低压直流、不拆市电设备”这一条");
inv.clearInventory();
inv.addToInventory([{ part: "a", from: "x", approx: true }, { part: "b", from: "x" }]);
inv.addToInventory([{ part: "a", from: "y", approx: true }]);
const r = inv.readInventory();
ok(r.length === 2 && r[0].n === 2 && r[0].from.join() === "x,y" && r[0].approx && !r[1].approx, "库存：累加数量、记来源、近似标记");
inv.removeFromInventory("a"); ok(inv.readInventory().length === 1, "库存：移除");
store[inv.INV_KEY] = "{bad json"; ok(inv.readInventory().length === 0, "库存：坏数据不崩");
inv.setProgress("micro-servo", { steps: [0, 2], mats: [1] }); ok(inv.readProgress("micro-servo").steps.join() === "0,2" && inv.readProgress("nope").steps.length === 0, "进度读写");
const src = ["src/teardown/devices.js", "src/pages/TeardownPage.jsx"].map((f) => fs.readFileSync(f, "utf8")).join("\n");
ok(!/<img|\.jpe?g|\.png|\.webp/i.test(src), "拆解页面不引用任何外部照片");
console.log(`teardown-test：${pass} PASS / ${fail} FAIL`);
process.exit(fail ? 1 : 0);
