import { chromium } from "playwright";
const br = await chromium.launch({ executablePath: "/usr/bin/google-chrome" });
const pg = await br.newPage({ viewport: { width: 1500, height: 1100 } });
const errs = []; pg.on("pageerror", (e) => errs.push(e.message)); pg.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await pg.goto("http://localhost:4173/repair");
console.log("sc buttons", await pg.locator("[data-testid^=sc-]").count(), "scope", await pg.locator("[data-testid^=scope-sc-]").count());
await pg.click("[data-testid=scope-sc-rig-missing-bulk]");
await pg.click("[data-testid=tool-scope]");
await pg.click("[data-testid=tp-TP5]"); await pg.click("[data-testid=tp-TP3]");
await pg.click("[data-testid=scope-exp-power]");
await pg.selectOption("[data-testid=scope-tdiv]", String(10e-3));
await pg.click("[data-testid=scope-capture]");
await pg.waitForFunction(() => window.__repair.scope.cap && !window.__repair.scope.busy, null, { timeout: 20000 });
console.log(await pg.locator("[data-testid=scope-readout]").innerText());
console.log(await pg.locator("[data-testid=scope-stats]").innerText());
console.log("bo lines", await pg.locator("[data-testid=scope-bo]").count());
await pg.locator("[data-testid=scope]").scrollIntoViewIfNeeded(); await pg.screenshot({ path: "/tmp/m3.png" });
console.log("errs", errs);
await br.close();
