// 电路实验页的端到端检查：node e2e/electrics.mjs（需要 vite preview 在 4173）
import { chromium } from "playwright";
import fs from "node:fs";
const OUT = process.env.OUT || "/workspace/proto-site/v4";
const BASE = process.env.BASE || "http://localhost:4173";
const b = await chromium.launch({ ...(process.env.CHROME ? { executablePath: process.env.CHROME } : {}) });
const p = await b.newPage({ viewport: { width: 1280, height: 1000 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
const res = {};
const glow = (id) => p.getByTestId(id).getAttribute("data-glow").then(Number);
await p.goto(BASE + "/electrics");
await p.getByTestId("elec-run").click();
await p.waitForTimeout(800);
res.idleGlowA = await glow("led-a");
await p.getByTestId("btn-a").hover(); await p.mouse.down(); await p.waitForTimeout(500);
res.pressedGlowA = await glow("led-a");
res.pressedmA = await p.getByTestId("led-a-ma").textContent();
await p.screenshot({ path: `${OUT}/elec-01-button-pressed.png` });
await p.mouse.up(); await p.waitForTimeout(400);
res.releasedGlowA = await glow("led-a");
await p.getByTestId("pot-a").fill("0.9"); await p.waitForTimeout(600);
res.linkHigh = await p.getByTestId("link-v").textContent();
res.glowB = await glow("led-b");
res.serialA = (await p.getByTestId("serial-a").textContent()).trim().split("\n").pop();
await p.getByTestId("pot-a").fill("0.1"); await p.waitForTimeout(600);
res.linkLow = await p.getByTestId("link-v").textContent();
res.glowBlow = await glow("led-b");
await p.getByTestId("r-select").selectOption("0");
await p.getByTestId("btn-a").hover(); await p.mouse.down(); await p.waitForTimeout(400);
res.noResistor = await p.getByTestId("led-a-ma").textContent();
await p.screenshot({ path: `${OUT}/elec-02-no-resistor.png` });
await p.mouse.up();
await p.goto(BASE + "/credits"); await p.screenshot({ path: `${OUT}/credits.png`, fullPage: true });
await p.goto(BASE + "/"); await p.screenshot({ path: `${OUT}/landing.png` });
res.errors = errs;
res.pass = res.idleGlowA === 0 && res.pressedGlowA > 0 && res.releasedGlowA === 0 && res.glowB > 0 && res.glowBlow === 0 && /烧坏/.test(res.noResistor) && errs.length === 0;
fs.writeFileSync(`${OUT}/electrics.json`, JSON.stringify(res, null, 2));
console.log(JSON.stringify(res, null, 2));
await b.close();
process.exit(res.pass ? 0 : 1);
